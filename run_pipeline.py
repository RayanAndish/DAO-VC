"""
run_pipeline.py
===============
Runs every step in order and stops at the first failure.
Generated files are removed before the run, so nothing from an earlier run is used silently.

Stages
  Data/01 .. 06   cleaning, calibration, cohort generation, training, proposal selection
  01 .. 03        (project root) Ganache deployment and on-chain tests, verified tables, figures
"""

import hashlib
import os
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent
DATA = ROOT / "Data"

STEPS = [
    (DATA, "01_clean_crunchbase.py", "Clean Crunchbase"),
    (DATA, "02_clean_user_behavior.py", "Clean telemetry"),
    (DATA, "03_calibrate_crunchbase_outcome.py", "Calibrate real-data outcome model"),
    (DATA, "04_generate_venture_cohort.py", "Generate venture cohorts"),
    (DATA, "05_train_models.py", "Train R(p) and B(u)"),
    (DATA, "06_score_proposals.py", "Select and score proposals"),
    (ROOT, "01_deploy_and_run_onchain.py", "Ganache deployment and on-chain tests"),
    (ROOT, "02_generate_verified_tables.py", "Verified tables"),
    (ROOT, "03_plot_publication_figures.py", "Publication figures"),
]

RAW_INPUTS = [
    DATA / "big_startup_secsees_dataset.csv",
    DATA / "user_behavior_dataset.csv",
]

# (folder, glob) pairs of generated files. Everything matched here is regenerated by the pipeline.
CLEAN_GLOBS = [
    (DATA, "crunchbase_clean.csv"),
    (DATA, "crunchbase_split_report.json"),
    (DATA, "user_behavior_clean.csv"),
    (DATA, "user_behavior_clean_report.json"),
    (DATA, "Table_Proposals_Feature_Profiles.csv"),
    (DATA, "proposal_selection.json"),
    (DATA / "models", "*"),
    (DATA / "cohorts", "venture_cohort_*.csv"),
    (DATA / "cohorts", "generator_report.json"),
    (DATA / "private", "*"),
    (ROOT, "OnChain_*.csv"),
    (ROOT, "Table_*.csv"),
    (ROOT, "Figure_*.png"),
]

PROVENANCE_FILES = [
    DATA / "crunchbase_split_report.json",
    DATA / "models" / "crunchbase_calibration.json",
    DATA / "cohorts" / "generator_report.json",
    DATA / "models" / "model_hash.json",
    DATA / "models" / "threshold.json",
    DATA / "models" / "train_report.json",
    DATA / "proposal_selection.json",
    DATA / "Table_Proposals_Feature_Profiles.csv",
    ROOT / "OnChain_Proposal_State_Raw.csv",
    ROOT / "OnChain_Test_Log.csv",
    ROOT / "Table_4_Treasury_Allocation.csv",
    ROOT / "Table_5_Ablation_Study.csv",
    ROOT / "Table_6_Sybil_Attack.csv",
    ROOT / "Table_7_Whale_Prioritization.csv",
    ROOT / "Table_8_Whale_Treasury_Distortion.csv",
    ROOT / "Table_8b_Whale_Worst_Case.csv",
]


def preflight():
    if not os.getenv("GANACHE_MNEMONIC"):
        sys.exit('[ERROR] GANACHE_MNEMONIC is not set. Use: set "GANACHE_MNEMONIC=word1 ... word12"')
    missing = [folder / name for folder, name, _ in STEPS if not (folder / name).is_file()]
    if missing:
        sys.exit(f"[ERROR] missing scripts: {[str(m.relative_to(ROOT)) for m in missing]}")
    absent = [p for p in RAW_INPUTS if not p.is_file()]
    if absent:
        sys.exit(f"[ERROR] missing raw inputs: {[p.name for p in absent]}")


def clear_generated():
    removed = 0
    for folder, pattern in CLEAN_GLOBS:
        for p in folder.glob(pattern):
            if p.is_file():
                p.unlink()
                removed += 1
    print(f"[*] removed {removed} generated file(s)", flush=True)


def run_step(number, total, folder, name, label):
    path = folder / name
    print("\n" + "=" * 80, flush=True)
    print(f"[STEP {number}/{total}] {path.relative_to(ROOT)}  -- {label}", flush=True)
    print("=" * 80, flush=True)
    t0 = time.time()
    result = subprocess.run([sys.executable, str(path)], cwd=str(folder), check=False)
    if result.returncode != 0:
        print(f"[FAILED] {name} exit code {result.returncode}. Pipeline stopped.", file=sys.stderr, flush=True)
        sys.exit(result.returncode)
    print(f"[OK] {name} ({time.time() - t0:.1f}s)", flush=True)


def sha256(p):
    return hashlib.sha256(p.read_bytes()).hexdigest()


def provenance():
    print("\n" + "=" * 80, flush=True)
    print("[DONE] provenance (SHA-256):", flush=True)
    for p in PROVENANCE_FILES:
        if p.is_file():
            print(f"  {sha256(p)}  {p.relative_to(ROOT)}", flush=True)
        else:
            print(f"  (missing)  {p.relative_to(ROOT)}", flush=True)
    print("=" * 80, flush=True)


def main():
    preflight()
    clear_generated()
    total = len(STEPS)
    start = time.time()
    for i, (folder, name, label) in enumerate(STEPS, 1):
        run_step(i, total, folder, name, label)
    print(f"\n[DONE] pipeline finished in {(time.time() - start) / 60:.1f} min", flush=True)
    provenance()


if __name__ == "__main__":
    main()